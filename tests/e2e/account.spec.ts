import { test, expect } from '@playwright/test'
import { ready, reset, signIn } from './helpers'

test.beforeEach(async ({ page }) => {
  await reset(page)
  await page.goto('/perfil')
  await signIn(page)
  await expect(page.getByRole('form', { name: 'Perfil do colecionador' })).toBeVisible()
})

test('edita perfil, apresenta conflito da API e persiste após refresh', async ({ page }) => {
  const form = page.getByRole('form', { name: 'Perfil do colecionador' })
  await form.getByLabel(/^Nome de usuário/).fill('leo.martins')
  await form.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(form.getByRole('alert')).toHaveText('Este nome de usuário já está em uso.')
  await form.getByLabel(/^Nome de usuário/).fill('nova.atualizada')
  await form.getByLabel(/^Nome de exibição/).fill('Nova Atualizada')
  await form.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(form.getByRole('status')).toHaveText('Perfil atualizado.')
  await page.reload()
  await ready(page)
  await expect(form.getByLabel(/^Nome de exibição/)).toHaveValue('Nova Atualizada')
  await expect(form.getByLabel(/^Nome de usuário/)).toHaveValue('nova.atualizada')
})

test('valida avatar, salva imagem e permite removê-la', async ({ page }) => {
  const upload = page.getByLabel('Arquivo de avatar')
  await upload.setInputFiles({ name: 'avatar.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') })
  await expect(page.getByRole('alert')).toHaveText('Envie uma imagem PNG, JPEG ou WebP de até 512 KB.')
  await upload.setInputFiles('public/assets/nfts/shades.webp')
  await expect(page.getByRole('status')).toHaveText('Avatar atualizado.')
  await expect(page.getByAltText('Seu avatar')).toBeVisible()
  await page.reload()
  await ready(page)
  await expect(page.getByAltText('Seu avatar')).toBeVisible()
  await page.getByRole('button', { name: 'Remover', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Avatar removido.')
  await expect(page.getByAltText('Seu avatar')).toBeHidden()
})

test('altera senha com validação e autentica apenas com a nova senha', async ({ page }) => {
  const form = page.getByRole('form', { name: 'Perfil do colecionador' })
  await form.getByLabel('Senha atual', { exact: true }).fill('incorreta123')
  await form.getByLabel('Nova senha', { exact: true }).fill('novaSenha123')
  await form.getByLabel('Confirmar nova senha', { exact: true }).fill('novaSenha123')
  await form.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(form.getByRole('alert')).toHaveText('Senha atual incorreta.')
  await form.getByLabel('Senha atual', { exact: true }).fill('kurio123')
  await form.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(form.getByRole('status')).toHaveText('Perfil e senha atualizados.')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/entrar')
  const login = page.getByRole('form', { name: 'Login' })
  await login.getByLabel('E-mail').fill('nova@kurio.dev')
  await login.getByLabel('Senha', { exact: true }).fill('kurio123')
  await login.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(login.getByRole('alert')).toHaveText('E-mail ou senha incorretos.')
  await signIn(page, 'nova@kurio.dev', 'novaSenha123')
})

test('edita e persiste carteiras principal/secundária, removendo apenas a secundária', async ({ page }) => {
  await page.getByRole('navigation', { name: 'Meu perfil' }).getByRole('link', { name: 'Carteiras' }).click()
  const primary = page.getByRole('form', { name: 'Carteira principal', exact: true })
  await primary.getByLabel(/^Endereço da carteira/).fill('inválido')
  await primary.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(primary.getByText('Use um endereço 0x com 40 caracteres hexadecimais.')).toBeVisible()
  await primary.getByLabel(/^Endereço da carteira/).fill('0x7a42c9d1e8b3f40a6c2d9e1b7f3a8c4d2e6b19e8')
  await primary.getByLabel(/^Apelido da carteira/).fill('Principal editada')
  await primary.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(primary.getByRole('status')).toHaveText('Carteira principal salva.')
  await page.getByLabel('Igual à carteira principal', { exact: true }).check()
  const secondary = page.getByRole('form', { name: 'Carteira secundária', exact: true })
  await secondary.getByLabel(/^Apelido da carteira/).fill('Reserva editada')
  await secondary.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(secondary.getByRole('status')).toHaveText('Carteira secundária salva.')
  await page.reload()
  await ready(page)
  await expect(primary.getByLabel(/^Apelido da carteira/)).toHaveValue('Principal editada')
  await expect(secondary.getByLabel(/^Apelido da carteira/)).toHaveValue('Reserva editada')
  await secondary.getByRole('button', { name: 'Remover carteira secundária' }).click()
  await secondary.getByRole('button', { name: 'Sim, remover' }).click()
  await expect(secondary).toBeHidden()
  await page.reload()
  await expect(primary.getByLabel(/^Apelido da carteira/)).toHaveValue('Principal editada')
  await expect(page.getByText('Você ainda não adicionou uma carteira secundária.')).toBeVisible()
})
