import { test, expect } from '@playwright/test'
import { addEmerald, ready, reset, reviewPurchase, signIn } from './helpers'

test.beforeEach(async ({ page }) => reset(page))

test('visitante compra, aguarda Socket.IO e recupera recibo após refresh', async ({ page }) => {
  await addEmerald(page)
  await page.evaluate(async () => {
    await window.__kurioMock!.setPaymentOutcome('hold')
  })
  const review = await reviewPurchase(page)
  await expect.poll(() => page.evaluate(() => window.__kurioMock!.realtime.connections().some((c) => c.userId === 'user_nova'))).toBe(true)
  await review.getByRole('button', { name: /^Confirmar e pagar/ }).click()
  await expect(page).toHaveURL(/\/pedido\/[^/]+$/)
  const receiptUrl = page.url()
  await expect(page.getByRole('heading', { name: 'Processando o pagamento…' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeHidden()
  await page.evaluate(() => window.__kurioMock!.settlePendingOrders('confirm'))
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('Emerald Ape #042')
  await expect(page.getByRole('link', { name: /Ver no Etherscan/ })).toBeVisible()
  const receipt = await page.getByRole('table').innerText()
  await page.evaluate(() => window.__kurioMock!.updateNft('emerald-ape-042', { priceEth: '9.99' }))
  await page.reload()
  await ready(page)
  await expect(page).toHaveURL(receiptUrl)
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  await expect(page.getByRole('table')).toHaveText(receipt, { useInnerText: true })
  await page.goto('/carrinho')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
})

test('logout e troca de conta não expõem carrinho ou pedido anterior', async ({ page }) => {
  await addEmerald(page)
  const review = await reviewPurchase(page)
  await review.getByRole('button', { name: /^Confirmar e pagar/ }).click()
  await expect(page).toHaveURL(/\/pedido\/[^/]+$/)
  const privateOrderUrl = page.url()
  await page.getByRole('link', { name: 'Fechar e voltar ao mercado' }).click()
  await page.getByRole('link', { name: /^(Conta|Minha conta)$/ }).click()
  await expect(page.getByRole('main')).toContainText('nova@kurio.dev')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.getByRole('link', { name: /^Carrinho,/ }).click()
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
  await page.getByRole('link', { name: 'Explorar o mercado', exact: true }).click()
  await page.getByRole('link', { name: /^(Conta|Entrar)$/ }).click()
  await signIn(page, 'leo@kurio.dev')
  await page.getByRole('link', { name: /^Carrinho,/ }).click()
  await expect(page.getByRole('main')).toContainText('Golden Beat #207')
  await expect(page.getByRole('main')).not.toContainText('Emerald Ape #042')
  await page.goto(privateOrderUrl)
  await expect(page.getByRole('heading', { name: 'Pedido não encontrado' })).toBeVisible()
  await expect(page.getByRole('table')).toBeHidden()
})

test('pagamento recusado preserva os itens e não mostra confirmação', async ({ page }) => {
  await addEmerald(page)
  await page.evaluate(() => window.__kurioMock!.setPaymentOutcome('hold'))
  const review = await reviewPurchase(page)
  await review.getByRole('button', { name: /^Confirmar e pagar/ }).click()
  await expect(page.getByRole('heading', { name: 'Processando o pagamento…' })).toBeVisible()
  await page.evaluate(() => window.__kurioMock!.settlePendingOrders('decline'))
  await expect(page.getByRole('heading', { name: 'Pagamento recusado' })).toBeVisible()
  await expect(page.getByRole('link', { name: /Ver no Etherscan/ })).toBeHidden()
  await page.getByRole('link', { name: 'Ver carrinho', exact: true }).click()
  await expect(page.getByRole('main')).toContainText('Emerald Ape #042')
})
