import { test, expect } from '@playwright/test'
import { addEmerald, ready, reset, signIn } from './helpers'

test.beforeEach(async ({ page }) => reset(page))

test('valida login e credenciais incorretas sem perder o contexto', async ({ page }) => {
  await page.goto('/pagamento')
  await expect(page).toHaveURL(/\/entrar\?redirect=/)
  const form = page.getByRole('form', { name: 'Login', exact: true })
  await form.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(form.getByText('Informe um e-mail válido.')).toBeVisible()
  await expect(form.getByText('Informe a senha.')).toBeVisible()
  await form.getByLabel('E-mail').fill('nova@kurio.dev')
  await form.getByLabel('Senha', { exact: true }).fill('senha-incorreta')
  await form.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(form.getByRole('alert')).toHaveText('E-mail ou senha incorretos.')
  await expect(form.getByLabel('E-mail')).toHaveValue('nova@kurio.dev')
  await signIn(page)
  await expect(page).toHaveURL(/\/pagamento$/)
})

test('cadastro trata conflito da API e cria uma conta persistente', async ({ page }) => {
  await page.goto('/entrar?modo=cadastro')
  const form = page.getByRole('form', { name: 'Cadastro', exact: true })
  await form.getByLabel('Nome de usuário', { exact: true }).fill('novo.colecionador')
  await form.getByLabel('E-mail', { exact: true }).fill('nova@kurio.dev')
  await form.getByLabel('Senha', { exact: true }).fill('novaSenha123')
  await form.getByLabel('Confirmar senha', { exact: true }).fill('diferente123')
  await form.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
  await expect(form.getByText('As senhas não conferem.')).toBeVisible()
  await form.getByLabel('Confirmar senha', { exact: true }).fill('novaSenha123')
  await form.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
  await expect(form.getByRole('alert')).toHaveText('Este e-mail já está cadastrado.')
  await form.getByLabel('E-mail', { exact: true }).fill('colecionador@kurio.dev')
  await form.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.goto('/entrar')
  await expect(page.getByRole('main')).toContainText('colecionador@kurio.dev')
  await page.reload()
  await ready(page)
  await expect(page.getByRole('main')).toContainText('colecionador@kurio.dev')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/entrar')
  await signIn(page, 'colecionador@kurio.dev', 'novaSenha123')
})

test('sessão expirada durante checkout retorna ao pagamento com o carrinho salvo', async ({ page }) => {
  await addEmerald(page)
  await page.getByRole('link', { name: 'Conectar e finalizar' }).click()
  await signIn(page)
  await expect(page).toHaveURL(/\/pagamento$/)
  await page.evaluate(() => window.__kurioMock!.expireSessions())
  await page.reload()
  await ready(page)
  await expect(page).toHaveURL(/\/entrar\?.*motivo=expirada/)
  await expect(page.getByText('Sua sessão expirou. Entre novamente para retomar de onde parou.')).toBeVisible()
  // A 401 may clear the token just before a refresh interrupts its redirect.
  // Entering the protected URL again must retain the reason for this same tab.
  await page.goto('/pagamento')
  await expect(page).toHaveURL(/\/entrar\?.*motivo=expirada/)
  await expect(page.getByText('Sua sessão expirou. Entre novamente para retomar de onde parou.')).toBeVisible()
  await signIn(page)
  await expect(page).toHaveURL(/\/pagamento$/)
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Revise sua compra' })).toContainText('Emerald Ape #042')
})

test('login mantém foco no diálogo e permite fechar pelo teclado', async ({ page }) => {
  await page.goto('/entrar')
  const dialog = page.getByRole('dialog', { name: 'Entrar', exact: true })
  await expect(dialog).toBeVisible()
  await page.getByLabel('E-mail', { exact: true }).focus()
  for (let i = 0; i < 15; i++) {
    await page.keyboard.press('Tab')
    await expect.poll(() => dialog.evaluate((node) => node.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page).toHaveURL(/\/$/)
})

test('login em andamento bloqueia edição e envio de outra identidade', async ({ page }) => {
  await page.goto('/entrar')
  await ready(page)
  await page.evaluate(() => window.__kurioMock!.setLatency(1500))
  const form = page.getByRole('form', { name: 'Login', exact: true })
  await form.getByLabel('E-mail', { exact: true }).fill('nova@kurio.dev')
  await form.getByLabel('Senha', { exact: true }).fill('kurio123')
  await form.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(form.getByLabel('E-mail', { exact: true })).toBeDisabled()
  await expect(form.getByLabel('Senha', { exact: true })).toBeDisabled()
  await expect(form.getByRole('button', { name: 'Aguarde…', exact: true })).toBeDisabled()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.goto('/entrar')
  await expect(page.getByRole('main')).toContainText('nova@kurio.dev')
})

test('retorno do login rejeita caminho que o navegador interpretaria como domínio externo', async ({ page }) => {
  await page.goto(`/entrar?redirect=${encodeURIComponent('/\\example.com')}`)
  await signIn(page)
  await expect(page).toHaveURL(/\/$/)
})
